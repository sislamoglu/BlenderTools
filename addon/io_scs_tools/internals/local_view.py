"""Expanding of Blender local view (isolate) on SCS Root objects.

Blender local view isolates only selected objects, so isolating SCS Root would show only the root empty.
Once 3D view enters local view with SCS Root in it, whole SCS Game Object (all objects within the root) is added to it.
Instances (collection, geometry nodes...) generated by the objects within the root follow their instancers automatically.

NOTE: Blender doesn't provide any handler for entering local view, thus entering is detected on 3D view redraw.
"""

import bpy
from io_scs_tools.utils import object as _object_utils

_expanded_spaces = set()
"""Pointers of 3D view spaces which local view was already expanded."""


def check_space(space):
    """Checks given 3D view space for entered local view and schedules its expansion. Should be called on 3D view redraw.

    :param space: 3D view space
    :type space: bpy.types.SpaceView3D
    """
    space_ptr = space.as_pointer()

    if space.local_view is None:
        _expanded_spaces.discard(space_ptr)
        return

    if space_ptr in _expanded_spaces:
        return

    _expanded_spaces.add(space_ptr)

    # NOTE: expand outside of drawing, as data shouldn't be changed while drawing
    bpy.app.timers.register(lambda: _expand_local_view(space_ptr), first_interval=0.0)


def _find_space(space_ptr):
    """Finds 3D view space with given pointer.

    :return: window, area and space; None if space doesn't exist anymore
    :rtype: (bpy.types.Window, bpy.types.Area, bpy.types.SpaceView3D) | None
    """
    for window in bpy.context.window_manager.windows:
        for area in window.screen.areas:
            if area.type == 'VIEW_3D' and area.spaces.active.as_pointer() == space_ptr:
                return window, area, area.spaces.active
    return None


def _expand_local_view(space_ptr):
    """Adds all objects within SCS Roots isolated in local view of given 3D view space to it.

    NOTE: Intended to be used as timer callback, thus returns None to be unregistered after the call.
    """
    found = _find_space(space_ptr)
    if found is None:
        return None

    window, area, space = found
    if space.local_view is None:
        return None

    view_layer = window.view_layer
    added_count = 0
    for obj in view_layer.objects:
        if obj.type != 'EMPTY' or obj.scs_props.empty_object_type != 'SCS_Root' or not obj.local_view_get(space):
            continue

        for child in _object_utils.get_children(obj):
            if child.name in view_layer.objects and not child.local_view_get(space):
                child.local_view_set(space, True)
                added_count += 1

    # frame whole isolated content, as local view was framed only on selected SCS Roots
    if added_count > 0:
        region = next((region for region in area.regions if region.type == 'WINDOW'), None)
        if region:
            with bpy.context.temp_override(window=window, area=area, region=region):
                bpy.ops.view3d.view_all()

    return None
